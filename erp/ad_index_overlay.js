// ⚠ DO NOT REMOVE — HS3 (bim-compiler prompts/TEAMWORK_FRAMEWORK.md §45.7): the twin's physical tables carried NO index at all, so every lookup by a foreign key (SELECT * FROM c_payment WHERE c_bpartner_id=?)
//   scanned the whole table and a head office slowed with every document it had already booked. Legacy iDempiere creates its official dictionary indexes (migration IDEMPIERE-1132 "Generate official dictionary
//   indexes": AD_TableIndex / AD_IndexColumn) on the physical tables; this is that list (ad_official_indexes.js, generated by patches/build_official_indexes.py from the migration, names resolved through the
//   twin's own dictionary), created as an idempotent boot OVERLAY exactly like ad_import_tables.js / ad_rule.js: NOT in a hashed patch, so the Team BASE hash does not move (W-BASE-EDIT / witness_team_base).
//   An index changes no result, only the plan: a table or column absent from this host's slice is skipped (counted), never an error. Unique indexes are not here (ad_ddl_unique carries them).
(function (global) {
  'use strict';
  function log(m) { try { console.log(m); } catch (e) {} }
  function list() { return global.AD_OFFICIAL_INDEXES || (typeof module !== 'undefined' && module.exports ? require('./ad_official_indexes.js') : []); }
  // ensure(db) - a sql.js Database. Returns { created, present, skipped, ms }.
  function ensure(db) {
    var t0 = Date.now(), made = 0, have = 0, skip = 0, tables = {}, haveIdx = {};
    try { (db.exec("SELECT name, tbl_name FROM sqlite_master WHERE type='index'")[0] || { values: [] }).values.forEach(function (v) { haveIdx[String(v[0]).toLowerCase()] = 1; }); } catch (e) {}
    (list() || []).forEach(function (e) {
      var p = String(e).split('|'), name = p[0], t = p[1], cs = p[2].split(',');
      if (haveIdx[name]) { have++; return; }
      if (!(t in tables)) { try { var r = db.exec('PRAGMA table_info("' + t + '")'); tables[t] = r.length ? r[0].values.map(function (v) { return String(v[1]).toLowerCase(); }) : null; } catch (x) { tables[t] = null; } }
      var have2 = tables[t];
      if (!have2 || !cs.every(function (c) { return have2.indexOf(c) >= 0; })) { skip++; return; }
      try { db.run('CREATE INDEX IF NOT EXISTS "' + name + '" ON "' + t + '" (' + cs.map(function (c) { return '"' + c + '"'; }).join(',') + ')'); made++; } catch (x) { skip++; }
    });
    var out = { created: made, present: have, skipped: skip, ms: Date.now() - t0 };
    log('§INDEX_OVERLAY ensure created=' + made + ' present=' + have + ' skipped=' + skip + ' ms=' + out.ms + ' (legacy official dictionary indexes, IDEMPIERE-1132; boot overlay, outside the team base hash)');
    return out;
  }
  var API = { ensure: ensure, list: list };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  global.AdIndexOverlay = API;
})(typeof window !== 'undefined' ? window : globalThis);
