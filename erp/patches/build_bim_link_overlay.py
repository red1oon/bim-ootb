#   the legacy plugin's OWN 2Pack (iDempiereOOTB/org.idempiere.bimootb/META-INF/2Pack_13.1.1.zip, made by iDempiere's Pack Out) - the same rows, the same UUs legacy Pack In creates.
#   Writes erp/ad_bim_link_rows.js; applied by erp/ad_bim_link_overlay.js (boot overlay, outside the team base hash). Rows of tables the Kernel does not use for this (the web-service
#   whitelist row: the Kernel push writes its store directly) are listed as skipped. Read the § line after a run.
# Usage: python3 erp/patches/build_bim_link_overlay.py <path to 2Pack_13.1.1.zip>
import hashlib, io, json, os, sys, zipfile
import xml.etree.ElementTree as ET
KEEP = ('AD_Element', 'AD_Column', 'AD_Field', 'AD_Tab')
src = sys.argv[1]
raw = open(src, 'rb').read()
z = zipfile.ZipFile(io.BytesIO(raw))
xml = next(n for n in z.namelist() if n.endswith('dict/PackOut.xml'))
root = ET.fromstring(z.read(xml))
rows, skipped = [], []
for e in root:
    if e.tag not in KEEP:
        skipped.append(e.tag); continue
    vals, refs = {}, {}
    for c in e:
        t = c.text if c.text is not None else None
        ref = c.attrib.get('reference')
        if ref:
            if t is None or t == '':
                continue
            refs[c.tag] = {'by': ref, 'table': c.attrib.get('reference-key'), 'key': t}
        elif t is not None:
            vals[c.tag] = t
    uu = vals.get(e.tag + '_UU')
    rows.append({'table': e.tag, 'uu': uu, 'vals': vals, 'refs': refs})
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ad_bim_link_rows.js')
meta = {'source': os.path.basename(src), 'sha256': hashlib.sha256(raw).hexdigest(), 'packVersion': root.attrib.get('Version'), 'packCreated': root.attrib.get('CreatedDate')}
with open(out, 'w') as f:
    f.write('// GENERATED by erp/patches/build_bim_link_overlay.py from the legacy plugin\'s ' + meta['source'] + ' (sha256 ' + meta['sha256'][:16] + ') - do not edit by hand.\n')
    f.write('// Applied by ad_bim_link_overlay.js (boot overlay, outside the team base hash). bim-compiler prompts/BIM_OOTB_LEGACY_IDEMPIERE_INTEGRATION.md §8.10.\n')
    f.write('(function (g) { var D = ' + json.dumps(dict(meta, rows=rows, skipped=skipped), indent=0, ensure_ascii=False).replace('\n', '') + ';\n')
    f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = D; g.AD_BIM_LINK_ROWS = D; })(typeof window !== 'undefined' ? window : globalThis);\n")
print('§BIMLINK_ROWS built rows=%d (%s) skipped=%s pack=%s sha256=%s -> %s' % (len(rows), ','.join(r['table'] for r in rows), ','.join(skipped) or '-', meta['packVersion'], meta['sha256'][:16], os.path.relpath(out)))
