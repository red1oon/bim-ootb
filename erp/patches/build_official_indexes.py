#!/usr/bin/env python3
# Builds erp/ad_official_indexes.js from legacy iDempiere's own index list: the migration IDEMPIERE-1132 "Generate official dictionary indexes"
# (idempiere/migration-historic/i2.0/postgresql/201312111413_IDEMPIERE-1132_OfficialIndexes.sql = AD_TableIndex + AD_IndexColumn rows), table / column ids resolved to NAMES
# through the twin's own dictionary (erp/ad_seed.db, whose ids ARE legacy's). Non-unique, plain-column indexes only (unique ones are ad_ddl_unique's).
# PLUS every plain `CREATE INDEX name ON table (cols)` the later official migrations (idempiere/migration/**/postgresql/*.sql) add, e.g. c_invoice_paid (IDEMPIERE-5259).
# Usage: python3 erp/patches/build_official_indexes.py [migration.sql] > erp/ad_official_indexes.js
import re, sqlite3, sys, os, json
here = os.path.dirname(os.path.abspath(__file__))
mig = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/idempiere-dev-setup/idempiere/migration-historic/i2.0/postgresql/201312111413_IDEMPIERE-1132_OfficialIndexes.sql')
db = sqlite3.connect(os.path.join(here, '..', 'ad_seed.db'))
tab = {r[0]: r[1].lower() for r in db.execute('select ad_table_id, tablename from ad_table')}
col = {r[0]: r[1].lower() for r in db.execute('select ad_column_id, columnname from ad_column')}
idx, cols = {}, {}
for ln in open(mig, encoding='utf8'):
    if ln.startswith('INSERT INTO AD_TableIndex '):
        m = re.search(r"VALUES \(\d+,\d+,(\d+),'[^']*',TO_TIMESTAMP\('[^']*','[^']*'\),\d+,'\w+','(\w)','([^']*)',TO_TIMESTAMP\('[^']*','[^']*'\),\d+,(\d+),'(\w)','(\w)','(\w)'\)", ln)
        if m: idx[int(m.group(1))] = {'name': m.group(3).lower(), 'table': int(m.group(4)), 'unique': m.group(6) == 'Y', 'active': m.group(2) == 'Y'}
    elif ln.startswith('INSERT INTO AD_IndexColumn '):
        m = re.search(r"VALUES \(\d+,\d+,\d+,\d+,'[^']*',TO_TIMESTAMP\('[^']*','[^']*'\),'\w+','(\w)',TO_TIMESTAMP\('[^']*','[^']*'\),\d+,(\d+),(\d+),(\d+)\)", ln)
        if m: cols.setdefault(int(m.group(2)), []).append((int(m.group(3)), int(m.group(4))))
out, skip = [], {'unique': 0, 'inactive': 0, 'unresolved': 0, 'functional': 0}
for i, d in sorted(idx.items()):
    if d['unique']: skip['unique'] += 1; continue
    if not d['active']: skip['inactive'] += 1; continue
    cs = [c for _, c in sorted(cols.get(i, []))]
    if not cs: skip['functional'] += 1; continue
    t = tab.get(d['table']); names = [col.get(c) for c in cs]
    if not t or not all(names): skip['unresolved'] += 1; continue
    out.append('%s|%s|%s' % (d['name'], t, ','.join(names)))
import glob
seen = set(x.split('|')[0] for x in out)
later = 0
for f in sorted(glob.glob(os.path.expanduser('~/idempiere-dev-setup/idempiere/migration/**/postgresql/*.sql'), recursive=True)):
    for m in re.finditer(r"(?im)^\s*create\s+index\s+(?:if\s+not\s+exists\s+)?(\w+)\s+on\s+(?:adempiere\.)?(\w+)\s*\(([^)]*)\)\s*;?\s*$", open(f, encoding='utf8', errors='replace').read()):
        n, t, cs = m.group(1).lower(), m.group(2).lower(), [re.sub(r'(?i)\s+(asc|desc)$', '', c.strip()).lower() for c in m.group(3).split(',')]
        if n in seen or not all(re.fullmatch(r'[a-z_0-9]+', c) for c in cs): continue
        seen.add(n); out.append('%s|%s|%s' % (n, t, ','.join(cs))); later += 1
skip['later_migrations_added'] = later
sys.stdout.write("""// Copyright (c) 2025-2026 Redhuan D. Oon <red1org@gmail.com>
// SPDX-License-Identifier: MIT
// GENERATED by erp/patches/build_official_indexes.py - do not edit. Legacy iDempiere's official non-unique dictionary indexes (IDEMPIERE-1132), name|table|columns.
// %d indexes (skipped: %s). Applied by ad_index_overlay.js as a boot overlay (NOT part of the hashed base patches).
(function (g) { g.AD_OFFICIAL_INDEXES = %s; })(typeof window !== 'undefined' ? window : globalThis);
if (typeof module !== 'undefined' && module.exports) module.exports = (typeof window !== 'undefined' ? window : globalThis).AD_OFFICIAL_INDEXES;
""" % (len(out), json.dumps(skip), json.dumps(out, separators=(',', ':'))))
