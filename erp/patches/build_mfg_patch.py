# ⚠ DO NOT REMOVE — scope: erp/patches/mfg.sql, the MANUFACTURING self-heal patch (~/Projects/Mfg/MILESTONE_1_SPEC.md, W-MFG-WIRE). Kept apart from
#   ad_seed.db.sql so the manufacturing layer can grow/ship/roll back on its own; idempiere.html applies it after ad_seed.db.sql on every load.
# EXTRACT ONLY from the reference Postgres `idempiere` (read-only): DDL for the 8 PP tables the bundle never shipped, the columns the two column-short
#   tables lack (PP_Order_Node 30/70, PP_Order_Cost 20/24), the 4 AD_Menu rows of the path 53014>53052>53053>53055 (IsActive forced 'Y': upstream ships
#   them 'N', EE01 off by default — an ordinary admin activation, precedent scripts/seed_hba_payroll_windows.js), and the physical column DEFAULTs
#   (ad_ddl_default) of the new tables. Idempotent, one statement per line (loader splits on ';\n'). Run: python3 build_mfg_patch.py > mfg.sql
import psycopg2, sys, datetime, decimal, os, sqlite3
cn = psycopg2.connect(host='localhost', user='adempiere', password='adempiere', dbname='idempiere'); cur = cn.cursor(); cur.execute('set search_path=adempiere')
def cols(t):
    cur.execute("select column_name, data_type from information_schema.columns where table_schema='adempiere' and table_name=%s order by ordinal_position", (t,)); return cur.fetchall()
def aff(d): return 'NUMERIC' if d in ('numeric', 'integer', 'bigint') else 'TEXT'
def lit(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return "'Y'" if v else "'N'"
    if isinstance(v, (int, float, decimal.Decimal)): return str(v)
    if isinstance(v, datetime.datetime): return "'" + v.strftime('%Y-%m-%d %H:%M:%S') + "'"
    if isinstance(v, datetime.date): return "'" + v.strftime('%Y-%m-%d') + " 00:00:00'"
    return "'" + str(v).replace("'", "''").replace('\n', ' ') + "'"
seed = sqlite3.connect(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ad_seed.db'))
NEW = ['pp_order_workflow', 'pp_order_node_product', 'pp_order_node_asset', 'pp_order_nodenext', 'pp_cost_collector', 'pp_cost_collectorma', 'pp_wf_node_product', 'pp_wf_node_asset']
SHORT = ['pp_order_node', 'pp_order_cost']
out = ['-- mfg.sql: Manufacturing layer self-heal patch (generated by erp/patches/build_mfg_patch.py from the idempiere Postgres DB). Idempotent.']
for t in NEW: out.append('CREATE TABLE IF NOT EXISTS %s (%s);' % (t, ', '.join('"%s" %s' % (c, aff(d)) for c, d in cols(t))))
for t in SHORT:   # a duplicate-column failure on re-run is tolerated by the loader (same precedent as fact_acct in ad_seed.db.sql)
    have = set(r[1].lower() for r in seed.execute('pragma table_info(%s)' % t))
    for c, d in cols(t):
        if c not in have: out.append('ALTER TABLE %s ADD COLUMN "%s" %s;' % (t, c, aff(d)))
# the 4 EE01 ad_menu rows (53014>53052>53053>53055) are NOT in this patch any more: upstream ships them disabled; the Libero bundle (erp/plugins/libero_manufacturing.mjs) stages them on activation (ctx.dict).
out.append('CREATE TABLE IF NOT EXISTS ad_ddl_default (tablename TEXT, columnname TEXT, defaultvalue TEXT);')
cur.execute("select table_name, column_name, column_default from information_schema.columns where table_schema='adempiere' and column_default is not null and table_name = any(%s) order by 1,2", (NEW,))
import re
for t, c, d in cur.fetchall():
    v = d.split('::')[0].strip()
    if v.startswith('(') and v.endswith(')'): v = v[1:-1]
    if v.startswith("'") and v.endswith("'"): v = v[1:-1]
    elif not re.match(r'^-?\d+(\.\d+)?$', v): continue
    out.append("INSERT INTO ad_ddl_default SELECT %s,%s,%s WHERE NOT EXISTS (SELECT 1 FROM ad_ddl_default WHERE tablename=%s AND columnname=%s);" % (lit(t), lit(c), lit(v), lit(t), lit(c)))
print('\n'.join(out))
print('§MFG-PATCH statements=%d' % (len(out) - 1), file=sys.stderr)
