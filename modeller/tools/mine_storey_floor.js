// Mines a rules DB's SOURCE storey floors into a self-heal patch: rule_storey_floor(storey, floor_z, provenance), floor_z in the rules' BAND frame.
// floor_z = the lowest IfcSlab top (center_z + bbox_z/2) of that storey in the source extraction, minus rules_meta.z_datum_offset. Only storeys the rule
// rows name (the base name of storey_scope, the text before " (") are mined; a multi-storey base ("/" or "+") is a set of names, each mined on its own.
// Usage: node modeller/tools/mine_storey_floor.js <source_extracted.db> <rules.db> > modeller/patches/<rules>.db.sql
'use strict';
const fs = require('fs'), path = require('path');
const initSqlJs = require(require.resolve('sql.js', { paths: [process.cwd(), path.join(process.env.HOME || '', 'bim-compiler', 'node_modules')] }));
const [SRC, RULES] = process.argv.slice(2);
if (!SRC || !RULES) { console.error('Usage: node modeller/tools/mine_storey_floor.js <source_extracted.db> <rules.db>'); process.exit(1); }
const rows = (db, s) => { const r = db.exec(s); return r.length ? r[0].values.map(v => Object.fromEntries(r[0].columns.map((c, i) => [c, v[i]]))) : []; };
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
(async () => {
  const SQL = await initSqlJs();
  const src = new SQL.Database(fs.readFileSync(SRC)), rul = new SQL.Database(fs.readFileSync(RULES));
  const off = +((rows(rul, "SELECT value FROM rules_meta WHERE key='z_datum_offset'")[0] || {}).value || 0);
  const base = s => String(s || '').split(' (')[0].trim();
  const names = new Set();
  rows(rul, 'SELECT DISTINCT storey_scope s FROM rule_placement').forEach(r => { base(r.s).split(/\s*[\/+]\s*/).forEach((n, i, a) => {
    // "Aras 01/02/03/04": the parts after the first carry only the number — complete them from the first part's prefix
    const full = i === 0 ? n : (/^\d+$/.test(n) ? a[0].replace(/\d+$/, n) : n); if (full) names.add(full); }); });
  const out = ['-- ⚠ DO NOT REMOVE — prompts/DISC_WALK_BAND_NO_HOST.md §12 rule 1. GENERATED by modeller/tools/mine_storey_floor.js; regenerate, do not hand-edit.',
    '-- source=' + path.basename(SRC) + ' rules=' + path.basename(RULES) + ' z_datum_offset=' + off,
    'CREATE TABLE IF NOT EXISTS rule_storey_floor(storey TEXT PRIMARY KEY, floor_z REAL, provenance TEXT);', 'DELETE FROM rule_storey_floor;'];
  let n = 0, miss = [];
  [...names].sort().forEach(s => {
    const r = rows(src, "SELECT COUNT(*) n, MIN(t.center_z + COALESCE(t.bbox_z,0)/2) top FROM elements_meta m JOIN element_transforms t ON t.guid=m.guid WHERE m.ifc_class='IfcSlab' AND m.storey=" + q(s))[0];
    if (!r || !r.n || r.top == null) { miss.push(s); return; }
    const z = +(r.top - off).toFixed(4);
    out.push('INSERT INTO rule_storey_floor VALUES(' + q(s) + ',' + z + ',' + q('measured:MIN(IfcSlab center_z+bbox_z/2)=' + (+r.top).toFixed(4) + ' over ' + r.n + ' slabs - z_datum_offset ' + off + ' : ' + path.basename(SRC)) + ');');
    n++;
  });
  process.stdout.write(out.join('\n') + '\n');
  console.error('§MINE-STOREY-FLOOR rows=' + n + ' missing=' + JSON.stringify(miss) + ' offset=' + off + ' names=' + names.size);
})();
