#!/usr/bin/env python3
# ⚠ DO NOT REMOVE — scope: §Q.55 (bim-compiler prompts/4D_MODEL_INTEGRITY.md). Read the printed §-lines after every run; exit code is not evidence.
# WHAT: for every element of a shipped DB, reads its OWN mesh (component_geometries, vertices float32 xyz stored relative to
#       element_transforms.center_*) and writes the middle of that mesh's box, in that local frame, as `element_box_offset(guid, ox, oy, oz)`
#       — an idempotent block in buildings/patches/<db>.sql, the file viewer/scene.js A._applyPendingPatch fetches by name and
#       scripts/lib/apply_building_patch.js applies in node. Never a binary DB. An extracted fact: nothing is computed but a min and a max.
# ISSUE IT PROVES OR DISPROVES: center_* is where the mesh is PLACED, not the middle of its box, so `center ± bbox/2` (what every 4D reader
#       did) is displaced on a third of the elements. viewer/schedule_gate.js ensureElementBox adds this offset to the centre.
# RULE: a row only where the offset exceeds 1 mm on some axis. (1 cm was tried first: the shipped judge, run on the true mesh boxes, then
#       disagreed with the schedule's own boxes on 15 Hospital elements — a contact test with an EPS flips on a centimetre.) AND the mesh's box size equals bbox_* within 1 cm (else the element is counted
#       and left without a row — its box is not the mesh's box for a reason this tool does not know). Rotated rows (rotation_* != 0) likewise.
# usage: python3 tools/element_box_offset_patch.py --db <meta or extracted .db> [--geo <_geo.db>] [--patch <file>] [--write]
import sys, os, sqlite3, argparse, collections
import numpy as np
BEGIN = '-- §ELEMENT_BOX_OFFSET BEGIN (generated by tools/element_box_offset_patch.py; re-run replaces this block)'
END = '-- §ELEMENT_BOX_OFFSET END'
DDL = 'CREATE TABLE IF NOT EXISTS element_box_offset (guid TEXT PRIMARY KEY, ox REAL NOT NULL, oy REAL NOT NULL, oz REAL NOT NULL);'
ap = argparse.ArgumentParser()
ap.add_argument('--db', required=True); ap.add_argument('--geo'); ap.add_argument('--patch'); ap.add_argument('--write', action='store_true')
a = ap.parse_args()
dbfile = os.path.basename(a.db)
patch = a.patch or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'buildings', 'patches', dbfile + '.sql')
con = sqlite3.connect('file:' + a.db + '?mode=ro', uri=True)
geo = sqlite3.connect('file:' + (a.geo or a.db) + '?mode=ro', uri=True)
cache, rows, n = {}, [], collections.Counter()
q = ('SELECT t.guid, t.bbox_x, t.bbox_y, t.bbox_z, ABS(COALESCE(t.rotation_x,0))+ABS(COALESCE(t.rotation_y,0))+ABS(COALESCE(t.rotation_z,0)), i.geometry_hash '
     'FROM element_transforms t JOIN element_instances i ON i.guid = t.guid ORDER BY t.guid')
for g, bx, by, bz, rot, h in con.execute(q):
    n['elements'] += 1
    if h not in cache:
        r = geo.execute('SELECT vertices FROM component_geometries WHERE geometry_hash = ?', (h,)).fetchone()
        if not r or not r[0] or len(r[0]) % 12: cache[h] = None
        else:
            v = np.frombuffer(r[0], dtype='<f4').reshape(-1, 3).astype(float); cache[h] = (v.min(0), v.max(0))
    if cache[h] is None: n['noMesh'] += 1; continue
    lo, hi = cache[h]
    if rot > 1e-9: n['rotated(no row)'] += 1; continue
    if bx is None or by is None or bz is None or max(abs((hi[0] - lo[0]) - bx), abs((hi[1] - lo[1]) - by), abs((hi[2] - lo[2]) - bz)) > 0.01: n['sizeDiffers(no row)'] += 1; continue
    o = (lo + hi) / 2
    if np.abs(o).max() <= 0.001: n['centred'] += 1; continue
    n['offset'] += 1; rows.append((g, round(float(o[0]), 4), round(float(o[1]), 4), round(float(o[2]), 4)))
mx = max((max(abs(r[1]), abs(r[2]), abs(r[3])) for r in rows), default=0)
print('§ELEMENT_BOX_OFFSET %s elements=%d rows=%d (max %.2f m) centred=%d noMesh=%d sizeDiffers=%d rotated=%d' % (
    dbfile, n['elements'], n['offset'], mx, n['centred'], n['noMesh'], n['sizeDiffers(no row)'], n['rotated(no row)']))
if not n['elements'] or n['noMesh'] == n['elements']: print('§ELEMENT_BOX_OFFSET INCONCLUSIVE — no mesh could be read (pass --geo for a _meta db)'); sys.exit(2)
block = [BEGIN, DDL, 'DELETE FROM element_box_offset;']
for k in range(0, len(rows), 400):
    block.append('INSERT OR REPLACE INTO element_box_offset (guid, ox, oy, oz) VALUES ' + ', '.join("('%s', %g, %g, %g)" % (r[0].replace("'", "''"), r[1], r[2], r[3]) for r in rows[k:k + 400]) + ';')
block.append(END)
if not a.write: print('§ELEMENT_BOX_OFFSET dry run — %d statements, not written (--write)' % (len(block) - 2)); sys.exit(0)
src = open(patch).read() if os.path.exists(patch) else ''
if BEGIN in src and END in src: src = src[:src.index(BEGIN)].rstrip('\n') + '\n' + src[src.index(END) + len(END):].lstrip('\n')
src = (src.rstrip('\n') + '\n\n' if src.strip() else '') + '\n'.join(block) + '\n'
open(patch, 'w').write(src)
print('§ELEMENT_BOX_OFFSET written %s statements=%d bytes=%d' % (patch, len(block) - 2, len(src)))
