#!/usr/bin/env python3
# ⚠ DO NOT REMOVE — scope: §Q.44 (bim-compiler prompts/4D_MODEL_INTEGRITY.md). Read the printed §-lines after every run; exit code is not evidence.
# WHAT: reads the SOURCE IFCs with IfcOpenShell and writes each IfcCovering's DECLARED PredefinedType (its own, else its type object's) as an
#       idempotent block in buildings/patches/<db>.sql — the file viewer/scene.js A._applyPendingPatch fetches by name and
#       scripts/lib/apply_building_patch.js applies in node. Never a binary DB. No computed value: an extracted fact only.
# ISSUE IT PROVES OR DISPROVES: §CEILING_CLOSEUP decided ceiling / floor finish from geometry; LTU's 24,321 coverings are declared INSULATION and
#       12,038 of them were scheduled as ceilings. viewer/shim_bonds.js kindOf reads `element_predefined_type` through the element's `ptype`.
# RULE: a row is kept only if the guid is an IfcCovering of the target DB. NOTDEFINED / USERDEFINED / absent on both the element and its type =
#       no row (undeclared: the schedule keeps its geometry rule for that element). Re-running replaces the block (BEGIN/END markers).
# COMPACT FORM: when EVERY IfcCovering of the DB was found and they all declare ONE type, the block is a single INSERT … SELECT over elements_meta
#       (the same rows; LTU would otherwise be 24,321 statements for the browser to run).
# usage: python3 tools/ifc_predefined_type_patch.py --db <path to the shipped .db> [--patch buildings/patches/<dbfile>.sql] [--write] a.ifc b.ifc ...
import sys, os, sqlite3, argparse, collections
import ifcopenshell

BEGIN = '-- §IFC_PREDEFINED_TYPE BEGIN (generated by tools/ifc_predefined_type_patch.py; re-run replaces this block)'
END = '-- §IFC_PREDEFINED_TYPE END'
DDL = 'CREATE TABLE IF NOT EXISTS element_predefined_type (guid TEXT PRIMARY KEY, predefined_type TEXT NOT NULL);'
UNDECLARED = (None, '', 'NOTDEFINED', 'USERDEFINED')

ap = argparse.ArgumentParser()
ap.add_argument('--db', required=True); ap.add_argument('--patch'); ap.add_argument('--write', action='store_true'); ap.add_argument('ifc', nargs='+')
a = ap.parse_args()
dbfile = os.path.basename(a.db)
patch = a.patch or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'buildings', 'patches', dbfile + '.sql')
con = sqlite3.connect('file:' + a.db + '?mode=ro', uri=True)
inDb = set(r[0] for r in con.execute("SELECT guid FROM elements_meta WHERE ifc_class='IfcCovering'"))
con.close()

def attr(e, name):
    try: return getattr(e, name, None)
    except Exception: return 'UNREADABLE'            # a malformed entity (fewer arguments than its schema) — counted, never guessed

def declared(e):
    pt = attr(e, 'PredefinedType')
    if pt == 'UNREADABLE': return pt
    if pt not in UNDECLARED: return str(pt)
    rels = attr(e, 'IsTypedBy') or [r for r in (attr(e, 'IsDefinedBy') or []) if r.is_a('IfcRelDefinesByType')]
    for r in (rels if rels != 'UNREADABLE' else []):
        tp = attr(r.RelatingType, 'PredefinedType')
        if tp not in UNDECLARED and tp != 'UNREADABLE': return str(tp)
    return None

got, unread, undecl = {}, 0, 0
for fp in a.ifc:
    if not os.path.isfile(fp): print('§PTYPE_SRC %s MISSING — INCONCLUSIVE for this file' % fp); continue
    f = ifcopenshell.open(fp); st = collections.Counter()
    for e in f.by_type('IfcCovering'):
        st['coverings'] += 1
        if e.GlobalId not in inDb: st['notInDb'] += 1; continue
        if e.GlobalId in got: st['dup'] += 1; continue
        d = declared(e)
        if d == 'UNREADABLE': st['unreadable'] += 1; unread += 1; continue
        if d is None: st['undeclared'] += 1; undecl += 1; continue
        got[e.GlobalId] = d; st['kept'] += 1
    print('§PTYPE_SRC %s schema=%s coverings=%d kept=%d notInDb=%d undeclared=%d unreadable=%d duplicateOfEarlierFile=%d%s' % (
        os.path.basename(fp), f.schema, st['coverings'], st['kept'], st['notInDb'], st['undeclared'], st['unreadable'], st['dup'], ' VACUOUS' if not st['coverings'] else ''))
    del f

by = collections.Counter(got.values())
print('§PTYPE_DB %s coveringsInDb=%d declared=%d undeclared=%d unreadable=%d notFoundInAnySource=%d byType=%s%s' % (
    dbfile, len(inDb), len(got), undecl, unread, len(inDb) - len(got) - undecl - unread, dict(by.most_common()),
    ' — INCONCLUSIVE: nothing declared, no block written' if not got else ''))
if not got: sys.exit(2)

uniform = len(by) == 1 and len(got) == len(inDb)
lines = [BEGIN, '-- %s: %d of %d IfcCovering carry a declared PredefinedType (%s). Sources: %s' % (
    dbfile, len(got), len(inDb), ', '.join('%s %d' % kv for kv in by.most_common()), ', '.join(os.path.basename(x) for x in a.ifc)), DDL, 'DELETE FROM element_predefined_type;']
if uniform:
    lines.append("INSERT OR REPLACE INTO element_predefined_type (guid, predefined_type) SELECT guid, '%s' FROM elements_meta WHERE ifc_class = 'IfcCovering';" % list(by)[0])
else:
    for g in sorted(got): lines.append("INSERT OR REPLACE INTO element_predefined_type (guid, predefined_type) VALUES ('%s','%s');" % (g.replace("'", "''"), got[g]))
lines.append(END)
block = '\n'.join(lines) + '\n'
print('§PTYPE_BLOCK %s form=%s statements=%d bytes=%d' % (dbfile, 'one INSERT…SELECT (every covering, one type)' if uniform else 'one row per guid', len(lines) - 2, len(block)))
if not a.write: print('§PTYPE_WRITE skipped (report only; pass --write)'); sys.exit(0)
cur = open(patch, encoding='utf-8').read() if os.path.exists(patch) else ''
ia, ib = cur.find(BEGIN), cur.find(END)
rest = (cur[:ia] + cur[ib + len(END):].lstrip('\n')) if (ia >= 0 and ib > ia) else cur
open(patch, 'w', encoding='utf-8').write(rest + ('' if rest.endswith('\n') or not rest else '\n') + block)
print('§PTYPE_WRITE %s replacedExistingBlock=%s' % (patch, ia >= 0))
