# ifc_storeys_patch.py — the patch SQL that gives an already-imported DB its `storey_elevation` table (§IFC_STOREYS, bim-compiler MODELLER_MASTER §G3 SPEC).
# Reads the STEP text directly: a second, independent reading of the same files `viewer/ifc_declared_storeys.js` reads through web-ifc, which
# witness_ifc_storeys.js compares. Usage: ifc_storeys_patch.py [--z-offset M] a.ifc b.ifc > patch.sql
import argparse, os, re, sys

SUFFIXES = [' Ceiling', ' TOS', ' T.O.S.', ' Top of Steel', ' Soffit']   # viewer/import_worker.js normalizeStorey, so names match elements_meta.storey
PREFIX = dict(EXA=1e18, PETA=1e15, TERA=1e12, GIGA=1e9, MEGA=1e6, KILO=1e3, HECTO=1e2, DECA=10, DECI=.1, CENTI=.01, MILLI=.001, MICRO=1e-6, NANO=1e-9, PICO=1e-12, FEMTO=1e-15, ATTO=1e-18)

def split_args(s):
    """Split one STEP attribute list on its top-level commas, quote and bracket aware."""
    out, cur, depth, q = [], '', 0, False
    for ch in s:
        if q:
            cur += ch
            if ch == "'": q = False
        elif ch == "'": q = True; cur += ch
        elif ch == '(': depth += 1; cur += ch
        elif ch == ')': depth -= 1; cur += ch
        elif ch == ',' and depth == 0: out.append(cur.strip()); cur = ''
        else: cur += ch
    out.append(cur.strip())
    return out

def unquote(s): return s[1:-1].replace("''", "'") if s.startswith("'") else None

def scale_of(lines, ref):
    m = lines.get(ref)
    if not m: return None
    ent, args = m
    a = split_args(args)
    if ent == 'IFCSIUNIT' and a[1] == '.LENGTHUNIT.':
        return PREFIX.get(a[2].strip('.'), 1.0)
    if ent == 'IFCCONVERSIONBASEDUNIT' and a[1] == '.LENGTHUNIT.':
        ent2, args2 = lines[a[3]]
        b = split_args(args2)
        v = float(re.search(r'\(([^)]+)\)', b[0]).group(1))
        base = scale_of(lines, b[1])
        return None if base is None else v * base
    return None

def read(path):
    txt = open(path, errors='replace').read()
    lines = {}
    for m in re.finditer(r'(#\d+)\s*=\s*(IFCUNITASSIGNMENT|IFCSIUNIT|IFCCONVERSIONBASEDUNIT|IFCMEASUREWITHUNIT)\((.*?)\);', txt, re.S):
        lines[m.group(1)] = (m.group(2), m.group(3))
    scale = None
    for ent, args in lines.values():
        if ent == 'IFCUNITASSIGNMENT':
            for ref in re.findall(r'#\d+', args):
                s = scale_of(lines, ref)
                if s is not None: scale = s; break
    rows = []
    for m in re.finditer(r'#\d+\s*=\s*IFCBUILDINGSTOREY\((.*?)\);', txt, re.S):
        a = split_args(m.group(1))
        rows.append(dict(guid=unquote(a[0]), raw=unquote(a[2]), elev=None if a[9] == '$' else float(a[9])))
    return scale, rows

def fold(name):
    low = name.strip().lower()
    for suf in SUFFIXES:
        if low.endswith(suf.lower()): return name.strip()[:-len(suf)].strip()
    return name.strip()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--z-offset', type=float, default=0.0, help='whole-metre z the import subtracted from every centre (project_metadata georef_offset_z)')
    ap.add_argument('ifc', nargs='+')
    args = ap.parse_args()
    q = lambda s: "'" + str(s).replace("'", "''") + "'"
    print('-- §IFC_STOREYS patch. Generated by tools/ifc_storeys_patch.py, read-only on the IFCs.')
    print('CREATE TABLE IF NOT EXISTS storey_elevation (guid TEXT PRIMARY KEY, name TEXT, elevation_attr_m REAL, placement_z_m REAL);')
    print('DELETE FROM storey_elevation;')
    for path in args.ifc:
        scale, rows = read(path)
        print('§IFC_STOREYS_PATCH file=%s unitScale=%s rows=%d' % (os.path.basename(path), scale, len(rows)), file=sys.stderr)
        if scale is None:
            print('§IFC_STOREYS_PATCH REFUSED %s no length unit in IfcUnitAssignment' % os.path.basename(path), file=sys.stderr)
            continue
        for r in rows:
            if r['elev'] is None or r['raw'] is None: continue
            name = fold(r['raw'])
            if name != r['raw'].strip(): continue   # a reference plane, as the importer treats it: no rung
            z = round(r['elev'] * scale - args.z_offset, 4) + 0.0
            print('INSERT OR REPLACE INTO storey_elevation VALUES (%s,%s,%r,NULL);' % (q(r['guid']), q(name), z))

if __name__ == '__main__': main()
