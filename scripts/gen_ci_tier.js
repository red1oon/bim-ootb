// ISSUE: 21 of 1,512 witness files run in CI. The fast tier is every headless witness whose LAST LOCAL RUN (witness_kit/results.js cache)
//   passed in under LIMIT seconds, needs no outside input and no browser. This writes the committed list tests/ci_fast_tier.json from that
//   cache; CI runs the list (scripts/run_ci_tier.js). Hand-kept: only `exclude` (a witness that cannot run on a runner, with the measured reason).
// USE:  node scripts/gen_ci_tier.js [--write] [--probe] [--limit 10]   (default: prints what --write would change; --probe: see below)
// Witness: scripts/tests/witness_ci_tier.js (W-CI-TIER). Read the log: the §CI_TIER line is the result.
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const RES = require('../witness_kit/results.js');
const LIST = 'tests/ci_fast_tier.json';
const BROWSER = /playwright|chromium|puppeteer|launchBrowser|find_browser|e2e_harness/;   // e2e_harness starts puppeteer (measured: 2 runner reds, 2026-11-18)

/** @returns {{list:object, why:Object<string,number>}} the list the cache says, keeping the committed `exclude` */
function generate(root, limit) {
  const cur = (() => { try { return JSON.parse(fs.readFileSync(path.join(root, LIST), 'utf8')); } catch (e) { return { exclude: [] }; } })();
  const excluded = new Set((cur.exclude || []).map(x => x.file));
  const tracked = new Set(cp.execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }).split('\n'));
  const why = { cached: 0, not_tracked: 0, not_pass: 0, slow: 0, browser: 0, excluded: 0, kept: 0 }, keep = [];
  let files = []; try { files = fs.readdirSync(RES.DIR()).filter(f => f.endsWith('.json')); } catch (e) { files = []; }
  for (const k of files) {
    let r; try { r = JSON.parse(fs.readFileSync(path.join(RES.DIR(), k), 'utf8')); } catch (e) { continue; }
    why.cached++;
    if (!tracked.has(r.file)) { why.not_tracked++; continue; }
    if (r.verdict !== 'PASS' || r.exit !== 0) { why.not_pass++; continue; }
    if (!(r.seconds < limit)) { why.slow++; continue; }
    if (BROWSER.test(fs.readFileSync(path.join(root, r.file), 'utf8'))) { why.browser++; continue; }
    if (excluded.has(r.file)) { why.excluded++; continue; }
    why.kept++; keep.push({ file: r.file, cwd: r.cwd || '', seconds: r.seconds });
  }
  keep.sort((a, b) => a.file < b.file ? -1 : 1);
  return { list: { limit_s: limit, note: 'generated by scripts/gen_ci_tier.js from the last local runs (witness_kit/results.js); edit only `exclude`', witnesses: keep, exclude: (cur.exclude || []).slice().sort((a, b) => a.file < b.file ? -1 : 1) }, why };
}
const text = l => JSON.stringify({ limit_s: l.limit_s, note: l.note }).slice(0, -1) + ',\n "witnesses": [\n' + l.witnesses.map(w => '  ' + JSON.stringify(w)).join(',\n') + '\n ],\n "exclude": [\n' + l.exclude.map(w => '  ' + JSON.stringify(w)).join(',\n') + '\n ]\n}\n';
module.exports = { generate, text, LIST };

if (require.main === module) {
  const argv = process.argv.slice(2), li = argv.indexOf('--limit'), limit = li >= 0 ? +argv[li + 1] : 10;
  const root = path.join(__dirname, '..'), g = generate(root, limit), t = text(g.list);
  const cur = (() => { try { return fs.readFileSync(path.join(root, LIST), 'utf8'); } catch (e) { return ''; } })();
  const secs = g.list.witnesses.reduce((n, w) => n + w.seconds, 0);
  console.log(`§CI_TIER limit_s=${limit} ${Object.entries(g.why).map(([k, v]) => k + '=' + v).join(' ')} total_s=${Math.round(secs)} changed=${t !== cur ? 'Y' : 'N'}${argv.includes('--write') ? ' written=' + (t !== cur ? 1 : 0) : ''}`);
  if (argv.includes('--write') && t !== cur) fs.writeFileSync(path.join(root, LIST), t);
  if (argv.includes('--probe')) {
    // run every listed witness the way CI will: no arguments, and none of the env settings that point a witness at an outside input on this
    // machine; a red goes to `exclude` with the measured reason (the CI run then confirms or adds more, from its own log)
    const { runOne } = require('./run_ci_tier.js'), env = Object.assign({}, process.env);
    for (const k of Object.keys(env)) if (/^(SHED_|BLD_DIR$|BUILDINGS_DIR$|NODE_PATH$|BIM_COMPILER_ROOT$|DXF_DB_DIR$|CODEFACTS_)/.test(k)) delete env[k];
    const l = JSON.parse(fs.readFileSync(path.join(root, LIST), 'utf8')); let moved = 0;
    for (const w of l.witnesses.slice()) {
      let r = runOne(w, 60000, env); if (!r.ok) r = runOne(w, 60000, env);
      if (r.ok) continue;
      moved++; l.witnesses = l.witnesses.filter(x => x.file !== w.file);
      l.exclude.push({ file: w.file, reason: 'probe ' + new Date().toISOString().slice(0, 10) + ': ' + r.v + ' exit=' + r.exit + ' — ' + r.tail.replace(/\/tmp\/[^/ ]+\//g, '').slice(0, 160) });
    }
    l.exclude.sort((a, b) => a.file < b.file ? -1 : 1);
    fs.writeFileSync(path.join(root, LIST), text(l));
    console.log(`§CI_TIER_PROBE ran=${l.witnesses.length + moved} kept=${l.witnesses.length} moved_to_exclude=${moved}`);
  }
}
