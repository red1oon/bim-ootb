#!/usr/bin/env python3
# ⚠ DO NOT REMOVE — scope: §Q.33.11 (bim-compiler prompts/4D_MODEL_INTEGRITY.md). Read the printed §-lines after every run.
# WHAT: reads the SOURCE IFCs with IfcOpenShell and writes the IFC assembly relation (IfcRelAggregates: RelatingObject -> RelatedObjects, by GlobalId)
#       as an idempotent block in buildings/patches/<db>.sql — the file viewer/scene.js A._applyPendingPatch fetches by name and
#       scripts/lib/apply_building_patch.js applies in node. Never a binary DB. No computed value: an extracted fact only.
# ISSUE IT PROVES OR DISPROVES: §ASSEMBLY_RULE (viewer/schedule_author.js assemblyRule) reads `rel_aggregates`; four shipped DBs (Duplex, HHS, JKR,
#       Clinic) had none, so W-FC-2 (viewer/tests/witness_floor_carriers.js) was INCONCLUSIVE and curtain-wall mullions were filed as structure.
# RULE: a pair is kept only if BOTH guids are in the target DB's elements_meta (the join §ASSEMBLY_RULE runs). Pairs the patch file already
#       carries outside this generator's block are not repeated. Re-running replaces the block (BEGIN/END markers).
# usage: python3 scripts/ifc_aggregates_patch.py --db <path to the shipped .db> [--patch buildings/patches/<dbfile>.sql] [--write] a.ifc b.ifc ...
#        (without --write: report only. Needs ifcopenshell importable.)
import sys, os, re, sqlite3, argparse
import ifcopenshell

BEGIN = '-- §REL_AGGREGATES BEGIN (generated by scripts/ifc_aggregates_patch.py; re-run replaces this block)'
END = '-- §REL_AGGREGATES END'
DDL = 'CREATE TABLE IF NOT EXISTS rel_aggregates (parent_guid TEXT NOT NULL, child_guid TEXT NOT NULL, PRIMARY KEY (parent_guid, child_guid));'

ap = argparse.ArgumentParser()
ap.add_argument('--db', required=True)
ap.add_argument('--patch')
ap.add_argument('--write', action='store_true')
ap.add_argument('ifc', nargs='+')
a = ap.parse_args()

dbfile = os.path.basename(a.db)
patch = a.patch or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'buildings', 'patches', dbfile + '.sql')
con = sqlite3.connect('file:' + a.db + '?mode=ro', uri=True)
inDb = set(r[0] for r in con.execute('SELECT guid FROM elements_meta'))
hasTable = bool(con.execute("SELECT 1 FROM sqlite_master WHERE name='rel_aggregates'").fetchone())
dbPairs = set(con.execute('SELECT parent_guid, child_guid FROM rel_aggregates').fetchall()) if hasTable else set()
con.close()

cur = open(patch, encoding='utf-8').read() if os.path.exists(patch) else ''
ia, ib = cur.find(BEGIN), cur.find(END)
rest = cur[:ia] + cur[ib + len(END):] if (ia >= 0 and ib > ia) else cur
carried = set(re.findall(r"INSERT OR IGNORE INTO rel_aggregates \(parent_guid,child_guid\) VALUES \('([^']*)','([^']*)'\)", rest))

src = {}   # (parent, child) -> first file that stated it
tot = dict(pairs=0, parentNotInDb=0, childNotInDb=0, dup=0)
for fp in a.ifc:
    if not os.path.isfile(fp):
        print('§REL_AGG_SRC %s MISSING — INCONCLUSIVE for this file' % fp); continue
    f = ifcopenshell.open(fp)
    st = dict(pairs=0, kept=0, parentNotInDb=0, childNotInDb=0, dup=0)
    for r in f.by_type('IfcRelAggregates'):
        par = r.RelatingObject
        if par is None: continue
        for o in (r.RelatedObjects or []):
            st['pairs'] += 1
            pg, cg = par.GlobalId, o.GlobalId
            if pg not in inDb: st['parentNotInDb'] += 1; continue
            if cg not in inDb: st['childNotInDb'] += 1; continue
            if (pg, cg) in src: st['dup'] += 1; continue
            src[(pg, cg)] = os.path.basename(fp); st['kept'] += 1
    for k in tot: tot[k] += st[k]
    print('§REL_AGG_SRC %s schema=%s sourcePairs=%d kept=%d droppedParentNotInDb=%d droppedChildNotInDb=%d duplicateOfEarlierFile=%d%s' % (
        os.path.basename(fp), f.schema, st['pairs'], st['kept'], st['parentNotInDb'], st['childNotInDb'], st['dup'], ' VACUOUS' if st['pairs'] == 0 else ''))
    del f

kept = set(src)
already = kept & carried
new = sorted(kept - carried)
print('§REL_AGG_DB %s elements_meta=%d sourcePairs=%d keptBothInDb=%d droppedParentNotInDb=%d droppedChildNotInDb=%d duplicate=%d | alreadyInPatchFile=%d newInBlock=%d | rawDbTable=%s rawDbPairs=%d%s' % (
    dbfile, len(inDb), tot['pairs'], len(kept), tot['parentNotInDb'], tot['childNotInDb'], tot['dup'], len(already), len(new),
    'yes' if hasTable else 'no', len(dbPairs), '' if kept else ' VACUOUS — nothing kept, nothing written'))
if not kept: sys.exit(2)

if a.write:
    q = lambda s: "'" + s.replace("'", "''") + "'"
    block = [BEGIN, '-- sources: ' + ', '.join(os.path.basename(x) for x in a.ifc),
             '-- IfcRelAggregates pairs with BOTH guids in elements_meta: %d (%d already carried earlier in this file, %d here)' % (len(kept), len(already), len(new)),
             '-- Witness: W-FC-2 (viewer/tests/witness_floor_carriers.js); spec bim-compiler prompts/4D_MODEL_INTEGRITY.md §Q.33.11']
    if not re.search(r'CREATE TABLE IF NOT EXISTS rel_aggregates', rest): block.append(DDL)
    block += ['INSERT OR IGNORE INTO rel_aggregates (parent_guid,child_guid) VALUES (%s,%s);' % (q(p), q(c)) for p, c in new]
    block.append(END)
    os.makedirs(os.path.dirname(patch), exist_ok=True)
    out = rest.rstrip('\n') + ('\n' if rest.strip() else '') + '\n'.join(block) + '\n' if new or not already else rest
    if not new:
        # everything is already carried by the file: no empty block (a stale block of an earlier run is removed)
        if rest != cur: open(patch, 'w', encoding='utf-8').write(rest)
        print('§REL_AGG_WRITE %s %s — every kept pair is already carried by the patch file' % (patch, 'stale block removed' if rest != cur else 'unchanged'))
    else:
        open(patch, 'w', encoding='utf-8').write(out)
        print('§REL_AGG_WRITE %s wrote block rows=%d bytes=%d' % (patch, len(new), len(out.encode('utf-8'))))
