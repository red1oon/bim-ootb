/**
 * gen_access_seed.js — writes common/comm/access_seed.sql: ONLY the AD rows the comm layer's write check reads
 * (erp/ad_access.js buildRole + RoleContext.canUpdate, the MRole.canUpdate port), as SQL text — instead of the phone
 * downloading the whole 27 MB erp/ad_seed.db. Spec: bim-compiler prompts/TEAMWORK_FRAMEWORK.md §14.2 / §13.5.
 * Text, not a .db: binary DB commits are banned (CLAUDE.md "DB CHANGES = MIGRATION SCRIPT"); regenerate, never hand-edit.
 * Self-check §SEED-EQ: for every role × client 11 × orgs {0, 11, 12, 50000} × tables {c_order, c_orderline, m_product,
 * x_unknown}, canUpdate on the slim seed == canUpdate on the full seed. Any difference → exit 1, file not written.
 * Run: node common/comm/tools/gen_access_seed.js   (cwd = bim-ootb repo root)
 */
'use strict';
var fs = require('fs'), path = require('path'), crypto = require('crypto');
var ROOT = path.join(__dirname, '..', '..', '..');
function req(m) { try { return require(m); } catch (e) { return require('/home/red1/bim-ootb/node_modules/' + m); } }
var initSqlJs = req('sql.js'), AD = require(path.join(ROOT, 'erp', 'ad_access.js'));
var TABLES = {   // table → the columns buildRole / canUpdate / the phone page read (nothing else ships)
  ad_table: ['ad_table_id', 'tablename', 'accesslevel'],
  ad_role: ['ad_role_id', 'name', 'userlevel', 'isaccessallorgs', 'ad_client_id', 'ad_org_id', 'isuseuserorgaccess'],
  ad_role_orgaccess: ['ad_role_id', 'ad_client_id', 'ad_org_id', 'isreadonly', 'isactive'],
  ad_table_access: ['ad_role_id', 'ad_table_id', 'accesstyperule', 'isexclude', 'isreadonly', 'isactive'],
  ad_window_access: ['ad_role_id', 'ad_window_id', 'isreadwrite', 'isactive'],
  ad_process_access: ['ad_role_id', 'ad_process_id', 'isreadwrite', 'isactive'],
  ad_form_access: ['ad_role_id', 'ad_form_id', 'isreadwrite', 'isactive'],
  ad_org: ['ad_org_id', 'name', 'ad_client_id']
};
function lit(v) { return v == null ? 'NULL' : (typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'"); }
// better-sqlite3-shaped shim over sql.js, as the browser pages use (comm_phone.html)
function shim(db) { return { prepare: function (sql) { return {
  get: function () { var st = db.prepare(sql); st.bind([].slice.call(arguments)); var r = st.step() ? st.getAsObject() : undefined; st.free(); return r; },
  all: function () { var st = db.prepare(sql); st.bind([].slice.call(arguments)); var o = []; while (st.step()) o.push(st.getAsObject()); st.free(); return o; } }; } }; }

(async function () {
  var SQL = await initSqlJs(), srcBytes = fs.readFileSync(path.join(ROOT, 'erp', 'ad_seed.db')), full = new SQL.Database(srcBytes);
  var out = ['-- access_seed.sql — GENERATED by common/comm/tools/gen_access_seed.js from erp/ad_seed.db sha1=' + crypto.createHash('sha1').update(srcBytes).digest('hex').slice(0, 12) + '. Do not edit.'];
  var counts = {};
  Object.keys(TABLES).forEach(function (t) {
    var have = full.exec('PRAGMA table_info("' + t + '")'); var cols = have.length ? have[0].values.map(function (v) { return String(v[1]).toLowerCase(); }) : [];
    var use = TABLES[t].filter(function (c) { return cols.indexOf(c) >= 0; });
    out.push('CREATE TABLE ' + t + ' (' + use.join(', ') + ');');
    var r = full.exec('SELECT ' + use.join(', ') + ' FROM ' + t + ' ORDER BY ' + use.slice(0, 2).join(', '));
    var rows = r.length ? r[0].values : []; counts[t] = rows.length;
    for (var i = 0; i < rows.length; i += 200) out.push('INSERT INTO ' + t + ' VALUES ' + rows.slice(i, i + 200).map(function (row) { return '(' + row.map(lit).join(',') + ')'; }).join(',') + ';');
  });
  var sql = out.join('\n') + '\n', slim = new SQL.Database(); slim.exec(sql);
  // §SEED-EQ — the slim seed must give the SAME write verdicts as the full one
  var roles = shim(full).prepare('SELECT ad_role_id AS id FROM ad_role ORDER BY ad_role_id').all().map(function (r) { return r.id; }), tested = 0, diff = [];
  function verdict(db, roleId, org, table) {
    var t = shim(db).prepare('SELECT ad_table_id AS id, accesslevel AS lvl FROM ad_table WHERE lower(tablename)=?').get(table);
    if (!t) return 'no-table'; var r; try { r = AD.buildRole(shim(db), roleId); } catch (e) { return 'no-role'; }
    var v = r.canUpdate(11, org, Number(t.id), t.lvl); return (v.allowed ? 'Y ' : 'N ') + v.reason; }
  roles.forEach(function (rid) { [0, 11, 12, 50000].forEach(function (org) { ['c_order', 'c_orderline', 'm_product', 'x_unknown'].forEach(function (tb) {
    tested++; var a = verdict(full, rid, org, tb), b = verdict(slim, rid, org, tb); if (a !== b) diff.push(rid + '/' + org + '/' + tb + ': ' + a + ' vs ' + b); }); }); });
  console.log('§SEED_COUNTS ' + JSON.stringify(counts));
  console.log('§SEED-EQ roles=' + roles.length + ' cases=' + tested + ' differences=' + diff.length + (diff.length ? ' first: ' + diff[0] : ''));
  if (!tested) { console.log('§SEED-EQ INCONCLUSIVE — nothing compared'); process.exit(1); }
  if (diff.length) { console.log('§SEED-EQ FAIL — access_seed.sql NOT written'); process.exit(1); }
  fs.writeFileSync(path.join(__dirname, '..', 'access_seed.sql'), sql);
  console.log('§SEED_WRITTEN common/comm/access_seed.sql bytes=' + Buffer.byteLength(sql) + ' (full seed bytes=' + srcBytes.length + ')');
})().catch(function (e) { console.log('🔴 ' + (e && e.stack || e)); process.exit(2); });
