// ⚠ DO NOT REMOVE — report_core.js: red1's `report` builds the SAME two drafts as the Viewer's bug reporter (viewer/helpers.js:259-350):
// a prefilled GitHub issue on red1oon/bim-ootb (What happened? · Environment table · the log in <details> · label bug · URL <= 8000) and an email
// (mailto: the owner's address, the log cut until the URL is <= 1800 — the OS mail-client ceiling, §BUGREPORT_MAILTO_LEN). bim-compiler prompts/CLI_ERP_IVR.md §28.
// PURE: no require, no process; nothing is sent from here — the person's own browser or mail client sends it. READ THE LOG of W-RED1-REPORT.
// Follow-up (one implementation): viewer/helpers.js could call this builder instead of its own copy.
(function (root) {
  'use strict';
  var REPO = 'https://github.com/red1oon/bim-ootb/issues/new', MAIL = 'red1org@gmail.com', GH_MAX = 8000, MAIL_MAX = 1800;
  // r = {line, why, status, gapKind, env:[[label, value]], logs:[…lines]}
  function what(r) { return 'red1 line: ' + r.line + '\nAnswer: ' + (r.status || '?') + (r.gapKind ? ' (gap: ' + r.gapKind + ')' : '') + '\n' + (r.why || ''); }
  function github(r) {
    var build = function (n) {
      var body = ['## What happened?', what(r), '', '## Environment', '| | |', '|---|---|'].concat((r.env || []).map(function (e) { return '| ' + e[0] + ' | ' + e[1] + ' |'; }),
        ['', '<details><summary>red1 § log (last ' + n + ' lines)</summary>', '', '```', (r.logs || []).slice(-n).join('\n') || '(no log lines)', '```', '</details>', '', '---', '_Auto-generated by the red1 report (same shape as the BIM OOTB bug reporter)_']).join('\n');
      return REPO + '?title=' + encodeURIComponent('red1 gap: ' + String(r.why || r.line).slice(0, 60)) + '&body=' + encodeURIComponent(body) + '&labels=bug';
    };
    var counts = [50, 20, 10, 5, 0], url = '';
    for (var i = 0; i < counts.length; i++) { url = build(counts[i]); if (url.length <= GH_MAX) break; }
    return url;
  }
  function email(r) {
    var build = function (n) {
      var body = ['Bug Report', '==========', '', 'Description: ' + what(r), '', 'Environment:'].concat((r.env || []).map(function (e) { return e[0] + ': ' + e[1]; }),
        ['', 'red1 § log (last ' + n + ' lines):', n ? (r.logs || []).slice(-n).join('\n') : '(omitted — mailto: length limit; use the GitHub issue for the full log)', '', '---', 'Auto-generated by the red1 report']).join('\n');
      return 'mailto:' + MAIL + '?subject=' + encodeURIComponent('red1 gap report — ' + String(r.why || r.line).slice(0, 50)) + '&body=' + encodeURIComponent(body);
    };
    var counts = [50, 20, 10, 5, 0], url = '';
    for (var i = 0; i < counts.length; i++) { url = build(counts[i]); if (url.length <= MAIL_MAX) break; }
    return url;
  }
  function draft(r) { return [what(r), ''].concat((r.env || []).map(function (e) { return e[0] + ': ' + e[1]; }), ['log lines: ' + (r.logs || []).length + ' (the last ones go with it)']).join('\n'); }
  var api = { github: github, email: email, draft: draft, REPO: REPO, GH_MAX: GH_MAX, MAIL_MAX: MAIL_MAX };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.ReportCore = api;
})(this);
